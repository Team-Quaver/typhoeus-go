// crossVectors 与 tools/gen_qmc_vectors.py（参考实现 tools/qmc_ref.py）配套：
// 用参考实现生成随机主密钥的 EKey + 密文片段，验证 Go 全链路与参考一致。
// 包内固化 qmc/vectors.json（20260928 种子）；外部向量可用 QMC_CROSS_VECTORS 覆盖。
type crossVectors struct {
	Ekey    string `json:"ekey"`
	Master  string `json:"master"` // hex
	Plain   string `json:"plain"`  // hex，密文对应位置 4096..4096+128 的明文
	Cipher  string `json:"cipher"` // hex，同位置密文
	Offset  int64  `json:"offset"`
}

func TestCrossVectors(t *testing.T) {
	path := os.Getenv("QMC_CROSS_VECTORS")
	if path == "" {
		// 包内固化向量（tools/gen_qmc_vectors.py 生成，unlock-music 语义参考实现
		// tools/qmc_ref.py 构造）；env 可指向外部更新的向量文件覆盖。
		path = "vectors.json"
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var vs []crossVectors
	if err := json.Unmarshal(raw, &vs); err != nil {
		t.Fatal(err)
	}
	for i, v := range vs {
		master, err := DecryptEkey(v.Ekey)
		if err != nil {
			t.Fatalf("case %d ekey: %v", i, err)
		}
		if !bytes.Equal(master, mustHex(t, v.Master)) {
			t.Fatalf("case %d master key mismatch", i)
		}
		c, err := NewCipher(master)
		if err != nil {
			t.Fatalf("case %d cipher: %v", i, err)
		}
		got := c.Decrypt(mustHex(t, v.Cipher), v.Offset)
		if !bytes.Equal(got, mustHex(t, v.Plain)) {
			t.Fatalf("case %d decrypt mismatch @%d", i, v.Offset)
		}
	}
}
