func TestGetSegmentKey(t *testing.T) {
	cases := []struct {
		id   int64
		seed byte
		hash float64
		want float64
	}{
		{1, 0, 12345.0, 0},
		{1, 123, 12345.0, 5018},
		{51, 35, 516402887.0, 28373784},
		{0, 66, 3908240000.0, 5921575757},
	}
	for _, c := range cases {
		if got := getSegmentKey(c.id, c.seed, c.hash); got != c.want {
			t.Fatalf("getSegmentKey(%d,%d,%v)=%v want %v", c.id, c.seed, c.hash, got, c.want)
		}
	}
}

