// genKey128 = [1..128]，用于 v1 变换测试。
func genKey128() [v1KeySize]byte {
	var k [v1KeySize]byte
	for i := range k {
		k[i] = byte(i + 1)
	}
	return k
}

func TestV1TransformStart(t *testing.T) {
	k := genKey128()
	data := []byte("igohj&pg{fo")
	for i := range data {
		data[i] = mapByteAt(&k, data[i], int64(i))
	}
	if !bytes.Equal(data, []byte("hello world")) {
		t.Fatalf("got %q", data)
	}
}

