func qrcF(state uint32, key []uint32) uint32 {
	t1 := ((state & 1) << 31) |
		((state & 0xF8000000) >> 1) |
		((state & 0x1F800000) >> 3) |
		((state & 0x01F80000) >> 5) |
		((state & 0x001F8000) >> 7)
	t2 := ((state & 0x0001F800) << 15) |
		((state & 0x00001F80) << 13) |
		((state & 0x000001F8) << 11) |
		((state & 0x0000001F) << 9) |
		((state & 0x80000000) >> 23)

	k0 := ((t1 >> 24) & 0xFF) ^ key[0]
	k1 := ((t1 >> 16) & 0xFF) ^ key[1]
	k2 := ((t1 >> 8) & 0xFF) ^ key[2]
	k3 := ((t2 >> 24) & 0xFF) ^ key[3]
	k4 := ((t2 >> 16) & 0xFF) ^ key[4]
	k5 := ((t2 >> 8) & 0xFF) ^ key[5]

	state = uint32(qrcSboxFlat[qrcSboxBit(k0>>2)])<<28 |
		uint32(qrcSboxFlat[64+qrcSboxBit(((k0&0x03)<<4)|(k1>>4))])<<24 |
		uint32(qrcSboxFlat[128+qrcSboxBit(((k1&0x0F)<<2)|(k2>>6))])<<20 |
		uint32(qrcSboxFlat[192+qrcSboxBit(k2&0x3F)])<<16 |
		uint32(qrcSboxFlat[256+qrcSboxBit(k3>>2)])<<12 |
		uint32(qrcSboxFlat[320+qrcSboxBit(((k3&0x03)<<4)|(k4>>4))])<<8 |
		uint32(qrcSboxFlat[384+qrcSboxBit(((k4&0x0F)<<2)|(k5>>6))])<<4 |
		uint32(qrcSboxFlat[448+qrcSboxBit(k5&0x3F)])

	return ((state >> 16) & 1) << 31 |
		((state >> 25) & 1) << 30 |
		((state >> 12) & 1) << 29 |
		((state >> 11) & 1) << 28 |
		((state >> 3) & 1) << 27 |
		((state >> 20) & 1) << 26 |
		((state >> 4) & 1) << 25 |
		((state >> 15) & 1) << 24 |
		((state >> 31) & 1) << 23 |
		((state >> 17) & 1) << 22 |
		((state >> 9) & 1) << 21 |
		((state >> 6) & 1) << 20 |
		((state >> 27) & 1) << 19 |
		((state >> 14) & 1) << 18 |
		((state >> 1) & 1) << 17 |
		((state >> 22) & 1) << 16 |
		((state >> 30) & 1) << 15 |
		((state >> 24) & 1) << 14 |
		((state >> 8) & 1) << 13 |
		((state >> 18) & 1) << 12 |
		((state >> 0) & 1) << 11 |
		((state >> 5) & 1) << 10 |
		((state >> 29) & 1) << 9 |
		((state >> 23) & 1) << 8 |
		((state >> 13) & 1) << 7 |
		((state >> 19) & 1) << 6 |
		((state >> 2) & 1) << 5 |
		((state >> 26) & 1) << 4 |
		((state >> 10) & 1) << 3 |
		((state >> 21) & 1) << 2 |
		((state >> 28) & 1) << 1 |
		((state >> 7) & 1)
}

func qrcCrypt(input []byte, key [][]uint32) []byte {
	s0, s1 := qrcInitialPermutation(input)
	for idx := 0; idx < 15; idx++ {
		previousS1 := s1
		s1 = qrcF(s1, key[idx]) ^ s0
		s0 = previousS1
	}
	s0 = qrcF(s1, key[15]) ^ s0
	return qrcInversePermutation(s0, s1)
}

func qrcKeySchedule(key []byte, mode int) [][]uint32 {
	// schedule[16][6]；mode: 1=ENCRYPT 0=DECRYPT
	schedule := make([][]uint32, 16)
	for i := range schedule {
		schedule[i] = make([]uint32, 6)
	}

	v0 := binary.LittleEndian.Uint32(key[0:4])
	v1 := binary.LittleEndian.Uint32(key[4:8])

	var c, d uint32
	for i, b := range qrcKeyPermC {
		var bit uint32
		if b < 32 {
			bit = (v0 >> (31 - b)) & 1
		} else {
			bit = (v1 >> (63 - b)) & 1
		}
		c |= bit << (31 - i)
	}
	for i, b := range qrcKeyPermD {
		var bit uint32
		if b < 32 {
			bit = (v0 >> (31 - b)) & 1
		} else {
			bit = (v1 >> (63 - b)) & 1
		}
		d |= bit << (31 - i)
	}

	for i := 0; i < 16; i++ {
		shift := uint(qrcKeyRndShift[i])
		c = ((c << shift) | (c >> (28 - shift))) & 0xFFFFFFF0
		d = ((d << shift) | (d >> (28 - shift))) & 0xFFFFFFF0

		togen := i
		if mode == qrcDecrypt {
			togen = 15 - i
		}
		for j := 0; j < 24; j++ {
			bit := (c >> (31 - qrcKeyCompression[j])) & 1
			schedule[togen][j/8] |= bit << (7 - (j % 8))
		}
		for j := 24; j < 48; j++ {
			bit := (d >> (31 - (qrcKeyCompression[j] - 27))) & 1
			schedule[togen][j/8] |= bit << (7 - (j % 8))
		}
	}
	return schedule
}

const (
	qrcEncrypt = 1
	qrcDecrypt = 0
)

func qrcTripledesKeySetup(key []byte, mode int) [][][]uint32 {
	if mode == qrcEncrypt {
		return [][][]uint32{
			qrcKeySchedule(key[0:], qrcEncrypt),
			qrcKeySchedule(key[8:], qrcDecrypt),
			qrcKeySchedule(key[16:], qrcEncrypt),
		}
	}
	return [][][]uint32{
		qrcKeySchedule(key[16:], qrcDecrypt),
		qrcKeySchedule(key[8:], qrcEncrypt),
		qrcKeySchedule(key[0:], qrcDecrypt),
	}
}

func qrcTripledesCrypt(data []byte, key [][][]uint32) []byte {
	out := data
	for i := 0; i < 3; i++ {
		out = qrcCrypt(out, key[i])
	}
	return out
}
