// 函数体逐行对齐 tripledes.py 的 initial_permutation / inverse_permutation / f /
// crypt / key_schedule / tripledes_key_setup / tripledes_crypt。
// 位运算统一用 uint32（Python 侧是 32 位无符号语义）。

func qrcSboxBit(a uint32) uint32 {
	return (a & 32) | ((a & 31) >> 1) | ((a & 1) << 4)
}

